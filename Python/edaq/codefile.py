"""Stores configuration and metadata as Python code.

A file is ordinary Python that assigns plain values to ``data``, so it can be
read and imported like any other module. Loading never executes it: the syntax
tree is checked and only literal values are accepted, so a setup copied from
elsewhere cannot run anything. MATLAB ``.m`` files in the grammar defined by
docs/FILE_FORMATS.md can be read too, without executing MATLAB.
"""
from __future__ import annotations

import ast
import math
import os
import re
from pathlib import Path

HEADER = "# Generated by Engine DAQ Telemetry. Plain values only.\nfrom math import inf, nan\n\n"


class CodeFileError(ValueError):
    pass


class UnsafeCode(CodeFileError):
    pass


def encode(value) -> str:
    return f"data = {_format(value, 0)}\n"


def write(path, value) -> None:
    """Save through a sibling temporary file, so a crash mid-write cannot
    destroy an existing file."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(HEADER + encode(value), encoding="utf-8")
    os.replace(temporary, path)


def read(path, tolerate_truncation: bool = False):
    path = Path(path)
    text = path.read_text(encoding="utf-8")
    try:
        if path.suffix == ".m":
            return decode_matlab(text, tolerate_truncation)
        return decode(text, tolerate_truncation)
    except CodeFileError as error:
        raise CodeFileError(f"Could not read {path}: {error}") from error


def append_line(value) -> str:
    return f"data.append({_format(value, None)})\n"


def decode(text: str, tolerate_truncation: bool = False):
    """Values from Python source, without executing it."""
    try:
        tree = ast.parse(text)
    except SyntaxError as error:
        if not tolerate_truncation:
            raise UnsafeCode(f"Not valid Python: {error}") from error
        complete = text[: text.rstrip("\n").rfind("\n") + 1] if "\n" in text.rstrip("\n") else ""
        return decode(complete, tolerate_truncation=False)
    data = None
    for statement in tree.body:
        if isinstance(statement, ast.ImportFrom) and statement.module == "math" \
                and all(alias.name in ("inf", "nan") for alias in statement.names):
            continue
        if isinstance(statement, ast.Assign) and len(statement.targets) == 1 \
                and isinstance(statement.targets[0], ast.Name) and statement.targets[0].id == "data":
            data = _literal(statement.value)
            continue
        if _is_data_append(statement):
            if not isinstance(data, list):
                raise UnsafeCode("data.append used before data was a list.")
            data.append(_literal(statement.value.args[0]))
            continue
        raise UnsafeCode(f"Only plain values are allowed. Not accepted on line {statement.lineno}.")
    return data


def _is_data_append(statement) -> bool:
    if not (isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Call)):
        return False
    call = statement.value
    return isinstance(call.func, ast.Attribute) and call.func.attr == "append" \
        and isinstance(call.func.value, ast.Name) and call.func.value.id == "data" \
        and len(call.args) == 1 and not call.keywords


def _literal(node):
    if isinstance(node, ast.Constant) and (node.value is None or isinstance(node.value, (bool, int, float, str))):
        return node.value
    if isinstance(node, ast.Name) and node.id in ("nan", "inf"):
        return math.nan if node.id == "nan" else math.inf
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
        operand = _literal(node.operand)
        if isinstance(operand, (int, float)) and not isinstance(operand, bool):
            return -operand
    if isinstance(node, ast.List):
        return [_literal(item) for item in node.elts]
    if isinstance(node, ast.Dict):
        if any(key is None for key in node.keys):
            raise UnsafeCode("Dictionary unpacking is not accepted.")
        return {_literal(key): _literal(value) for key, value in zip(node.keys, node.values)}
    raise UnsafeCode(f"Only plain values are allowed. Not accepted on line {getattr(node, 'lineno', '?')}.")


def _format(value, indent):
    if hasattr(value, "tolist"):      # numpy arrays and scalars
        value = value.tolist()
    if value is None or isinstance(value, (bool, str, int)):
        return repr(value)
    if isinstance(value, float):
        if math.isnan(value):
            return "nan"
        if math.isinf(value):
            return "inf" if value > 0 else "-inf"
        return repr(value)
    inner = None if indent is None else indent + 4
    if isinstance(value, (list, tuple)):
        if indent is None or all(not isinstance(item, (dict, list, tuple)) for item in value):
            return "[" + ", ".join(_format(item, None) for item in value) + "]"
        pad = " " * inner
        return "[\n" + "".join(f"{pad}{_format(item, inner)},\n" for item in value) + " " * indent + "]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        for key in value:
            if not isinstance(key, str):
                raise CodeFileError(f"Keys must be text, not {type(key).__name__}.")
        if indent is None:
            return "{" + ", ".join(f"{key!r}: {_format(item, None)}" for key, item in value.items()) + "}"
        pad = " " * inner
        return "{\n" + "".join(f"{pad}{key!r}: {_format(item, inner)},\n" for key, item in value.items()) + " " * indent + "}"
    raise CodeFileError(f"Values of type {type(value).__name__} cannot be stored.")


_NUMBER = r"(?:-?(?:\d+(?:\.\d*)?(?:[eE][+-]?\d+)?|Inf)|NaN)"
_TEXT = r'"(?:[^"]|"")*"'
_ATOM = rf"(?:{_NUMBER}|true|false)"
_FORMS = re.compile(
    rf"^(?:(?P<atom>{_ATOM})|(?P<array>\[{_ATOM}(?:[ ;] ?{_ATOM})*\])|(?P<text>{_TEXT}(?: \+ newline \+ {_TEXT})*)"
    rf"|(?P<texts>\[{_TEXT}(?:[,;] {_TEXT})*\])|(?P<empty>\[\]|\{{\}}|struct\(\)|struct\(\[\]\)|strings\(\d+, \d+\)))$"
)
_TARGET = re.compile(r"^data(?:\.[A-Za-z]\w*|\{\d+\}|\(\d+\))*$")
_PART = re.compile(r"\.([A-Za-z]\w*)|[{(](\d+)[)}]")


def decode_matlab(text: str, tolerate_truncation: bool = False):
    """Values from a MATLAB code file. The file is parsed, never run."""
    lines = [line.strip() for line in text.splitlines()]
    lines = [line for line in lines if line and not line.startswith("%")]
    if lines and re.match(r"^function data = [A-Za-z]\w*(\(\))?$", lines[0]):
        lines.pop(0)
    holder = {"data": None}
    for k, line in enumerate(lines):
        parsed = _matlab_statement(line)
        if parsed is None:
            if tolerate_truncation and k == len(lines) - 1:
                break
            raise UnsafeCode(f"Only plain values are allowed. Not accepted: {line}")
        _assign(holder, parsed[0], parsed[1])
    return holder["data"]


def _matlab_statement(line: str):
    if " = " not in line or not line.endswith(";"):
        return None
    target, value = line[:-1].split(" = ", 1)
    match = _FORMS.match(value)
    if not _TARGET.match(target) or match is None:
        return None
    parts = [field if field else int(index) - 1 for field, index in _PART.findall(target)]
    return parts, _matlab_value(match)


def _matlab_value(match):
    if match["atom"]:
        return _matlab_atom(match["atom"])
    if match["array"]:
        rows = [[_matlab_atom(item) for item in row.split()] for row in match["array"][1:-1].split(";")]
        return rows[0] if len(rows) == 1 else ([row[0] for row in rows] if all(len(r) == 1 for r in rows) else rows)
    if match["text"]:
        return "\n".join(item.replace('""', '"') for item in re.findall(r'"((?:[^"]|"")*)"', match["text"]))
    if match["texts"]:
        return [item.replace('""', '"') for item in re.findall(r'"((?:[^"]|"")*)"', match["texts"])]
    return {"struct()": {}, "[]": None}.get(match["empty"], [])


def _matlab_atom(token: str):
    if token in ("true", "false"):
        return token == "true"
    return float(token.replace("Inf", "inf").replace("NaN", "nan"))


def _assign(holder, parts, value) -> None:
    node, key = holder, "data"
    for part in parts:
        if isinstance(node, dict):
            current = node.get(key)
        else:
            current = node[key] if key < len(node) else None
        if isinstance(part, str):
            if not isinstance(current, dict):
                current = {}
        elif not isinstance(current, list):
            current = []
        _store(node, key, current)
        node, key = current, part
    _store(node, key, value)


def _store(node, key, value) -> None:
    if isinstance(node, list):
        node.extend([None] * (key + 1 - len(node)))
    node[key] = value
